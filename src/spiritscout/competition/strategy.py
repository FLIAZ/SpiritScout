"""竞赛解题策略提示：目标是单位时间得分，不是完整研究或赛后写作。"""

from __future__ import annotations

from spiritscout.competition.rules import ContestType


def competition_strategy_prompt(contest_type: ContestType | str) -> str:
    """返回竞赛总控策略；约束由模型结合现场执行，不写死题目顺序。"""
    contest = (contest_type.value if isinstance(contest_type, ContestType)
               else str(contest_type))
    contest_note = {
        "jeopardy": "多题计分时持续比较尚未完成题目的预计得分效率。",
        "range": "靶场题按赛题入口工作，不把赛方管理平台当成扩展攻击面。",
        "awd": "轮次计分时每轮单独判断有效目标，不把一场成功当作永久完成。",
    }.get(contest, "按赛制与平台完成态判断可得分目标。")
    return (
        "竞赛策略：本会话的首要目标是单位时间内获得更多平台确认的有效分数，"
        "而不是充分研究、写题解或扩展无关攻击面。先处理题干清楚、入口明确、"
        "预计耗时短的题；难度相近时再比较分值与资源占用。信息不足时只做轻量"
        "判断，不为了精确排名额外调查。"
        f"{contest_note}"
        "某题反复尝试仍无新增有效信息、关键前提缺失或继续投入的预期收益明显"
        "低于其他未完成题时，由你判断是否暂缓：停止该题继续派发，确认同题在途"
        "工作已结束后关闭其平台容器，留下题号、阻塞原因、证据引用和值得重试的"
        "新条件；暂缓题不要自动换角度重攻，除非出现实质新线索、阻塞解除、容易题"
        "已处理完或用户明确要求。判断与重试时机由你结合现场决定，没有固定次数。"
        "平台确认提交正确后，该得分目标立即结束：不再反思解法、复测、扩展利用"
        "或生成 WP。多 Flag 题与 AWD 轮次只结束已经确认的得分目标，其余独立目标"
        "仍按得分效率比较。"
        "赛方管理平台只用于列题、读取题面、启停容器、提交与确认；题目靶机或附件"
        "才是解题对象，不主动研究平台后台、无关接口、其他用户或其他非必要信息。"
        "赛后可沉淀经验，但必须异步进行，不占用当前比赛的执行、容器或模型优先"
        "资源，也不阻塞结果交付。现有审批、授权边界和危险操作确认不变。"
    )


def competition_solver_prompt() -> str:
    """专项执行者的竞赛纪律：快速验证、及时收尾、不写 WP。"""
    return (
        "当前是多题竞赛/靶场语境：只围绕分配给你的赛题工作，优先用最少步骤"
        "验证最直接的得分线索。连续尝试没有新增有效信息、遇到同一阻塞或关键"
        "前提缺失时，给出简明阻塞结论并收尾，不在本题内无限换壳或重复验证；"
        "容器关闭和切题由灵枢统一协调，不要继续访问准备暂缓的实例。"
        "平台确认 Flag 正确后立即停止该得分目标的后续工作，不再反思、复测、扩展"
        "利用或写 WP。不要研究赛方管理平台的无关页面、接口或实现，只使用题目"
        "靶机、附件和解题所需的最小平台事实。"
    )
