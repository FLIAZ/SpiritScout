"use strict";
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const context=vm.createContext({esc:value=>String(value).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]))});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/spiritscout/web/static/js/skill-markdown-editor.js'),'utf8'),context);
const api=vm.runInContext('SkillMarkdownEditor',context);
const source='---\r\nname: fixture\r\ndescription: 保留元数据\r\n---\r\n\r\n# 标题\r\n\r\n正文 **粗体** 和 [参考](references/a.md)。\r\n\r\n- 原列表\r\n  - 嵌套项\r\n\r\n| A | B |\r\n| :--- | ---: |\r\n| 原文 | `a\\|b` |\r\n\r\n```python\r\nprint("保留代码")\r\n```\r\n\r\n> 引用\r\n\r\n![不加载外部图片](https://example.test/a.png)\r\n<script>bad()</script>\r\n';
const parsed=api.parse(source);
assert.equal(parsed.prefix+parsed.blocks.map(block=>block.raw).join(''),source,'未修改时完全保留原始 Markdown、CRLF 和 frontmatter');
assert(parsed.blocks.some(block=>block.kind==='table'));
assert(parsed.blocks.some(block=>block.kind==='code'&&block.info==='python'));
assert.equal(api.parse('没有换行').blocks[0].raw,'没有换行');
assert.equal(api.parse('```\nnot closed').blocks[0].closed,false);
assert.equal(api.tableCells('| A | `a\\|b` |').length,2);
assert.match(api.inlineHtml('**粗体** 与 *斜体* 和 `x<y`'),/<strong>粗体<\/strong>/);
assert.match(api.inlineHtml('<img src=x onerror=bad()>'),/&lt;img/);
assert.doesNotMatch(api.inlineHtml('[bad](javascript:alert)'),/<a/);
assert.match(api.inlineHtml('[根文件](references/a.md)'),/<a href="references\/a.md">/);
assert(!api.inlineHtml('`x\\|y`').includes('\uE000'),'代码内转义不泄漏内部标记');
assert(!api.inlineHtml('[`code`](notes.md)').includes('\uE000'),'嵌套引用正确展开内部标记');
const text=value=>({nodeType:3,textContent:value});
const element=(tag,...children)=>({nodeType:1,tagName:tag.toUpperCase(),childNodes:children,get textContent(){return children.map(child=>child.textContent).join('');}});
assert.equal(api.inlineMarkdown(element('strong',text('粗体'))),'**粗体**');
assert.equal(api.inlineMarkdown(element('p',text('第一行'),element('div',text('第二行')))),'第一行\n第二行\n\n');
assert.equal(api.inlineMarkdown(element('code',text('x`y'))),'``x`y``');
console.log('skill Markdown editor: lossless untouched blocks, frontmatter, CRLF, nested lists, code fences, escaped tables, safe links and inline serialization passed');
const image='![原图片](assets/example.png)';
assert.match(api.inlineHtml(image),/data-skill-md-literal/);
assert.doesNotMatch(api.inlineHtml(image),/<img/,'图片引用只展示文字，不发起外部加载');
assert.equal(api.inlineMarkdown({nodeType:1,tagName:'SPAN',hasAttribute:()=>true,getAttribute:()=>image}),image,'同段其它内容编辑后仍保留图片 Markdown 引用');
