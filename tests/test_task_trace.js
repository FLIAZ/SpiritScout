"use strict";
const assert=require("node:assert/strict"), fs=require("node:fs"), vm=require("node:vm"), path=require("node:path");
const context=vm.createContext({SessionObserver:{toolName:n=>n || "工具",cleanText:v=>String(v),resultSummary:d=>d.note || d.error || "返回结果"}});
vm.runInContext(fs.readFileSync(path.join(__dirname,"../src/spiritscout/web/static/js/task-trace.js"),"utf8"),context);
const api=vm.runInContext("TaskTrace",context), store=api.create();
let seq=0;
const push=(type,detail,actor="recon-one")=>api.reduce(store,{type,detail,actor,seq:++seq,ts:"now"});
assert.equal(push("agent.delta",{text:"主会话消息"},"master-123"),null);
push("task.start",{task_id:"a",title:"核实入口"});
push("task.start",{task_id:"b",title:"核对权限"});
push("agent.turn",{task_id:"a",route_id:"ra",route:"同名路线",turn:1});
push("agent.turn",{task_id:"b",route_id:"rb",route:"同名路线",turn:1});
const a=push("agent.tool_call",{task_id:"a",route_id:"ra",calls:[{id:"repeated",name:"http_request",arguments:{url:"https://a.test"}}]});
const b=push("agent.tool_call",{task_id:"b",route_id:"rb",calls:[{id:"repeated",name:"shell",arguments:{command:"pwd"}}]});
push("agent.tool_result",{task_id:"a",route_id:"ra",id:"repeated",ok:true,result:{code:200}});
assert.equal([...a.tools.values()][0].status,"done");
assert.match([...a.tools.values()][0].result,/"code": 200/);
assert.equal([...b.tools.values()][0].status,"running","并行任务复用调用 ID 不串结果");
push("agent.delta",{route_id:"ra",kind:"text",text:"已确认入口，下一步核对响应。",turn:1});
assert.match(api.updatesOf(a)[0].text,/已确认入口/);
push("agent.delta",{route_id:"ra",kind:"reasoning",text:"x".repeat(10000),turn:1});
assert.equal(a.texts.size,1,"分析详情沿用工作台，主进度不重复输出思考正文");
push("agent.conclude",{task_id:"a",route_id:"ra",summary:"入口可访问；尚未认证。"});
push("task.done",{task_id:"a",summary:{routes_total:1,routes_done:1}});
assert.equal(a.status,"done");
assert.equal(api.summaryOf(a),"入口可访问；尚未认证。");
assert.equal(b.status,"running");
const ambiguous=push("agent.delta",{route:"同名路线",text:"无法确定出处",kind:"text"});
assert.equal(ambiguous.id,"","旧记录同名路线有歧义时不能指向碰巧仍执行中的任务");
const old=push("task.done",{task_id:"history",summary:{routes_total:2,routes_done:2},conclusions:[{route:"a",text:"第一条产出"},{route:"b",text:"第二条产出"}]});
assert.equal(api.summaryOf(old),"第一条产出\n\n第二条产出","只回放完成事件也有真实摘要");
const missing=push("agent.tool_result",{task_id:"old-tool",id:"no-call",ok:false,error:"请求超时"});
assert.equal([...missing.tools.values()][0].missingCall,true);
assert.equal([...missing.tools.values()][0].status,"failed");
const ended=push("task.failed",{task_id:"old-tool",error:"环境不可达"});
assert.equal(api.summaryOf(ended),"环境不可达");
const page=api.create();
const callsOnly=api.reduce(page,{actor:"recon-page",type:"task.done",detail:{task_id:"x",summary:{routes_total:3,routes_done:2}}});
assert.match(api.summaryOf(callsOnly),/路线完成 2\/3/);
assert.match(api.summaryOf(callsOnly),/未包含文字结论/);
console.log("task trace: parallel task isolation, nested tool data, truthful summaries, partial history and failures passed");

// 模型正文在工具往返后仍保留，不再被工具状态覆盖或收进工具总折叠块。
const narrative=api.create();
let stamp=0;
const explain=(type,detail)=>api.reduce(narrative,{actor:"web-one",type,detail,seq:++stamp,ts:"now"});
explain("task.start",{task_id:"n",title:"核实登录行为"});
const first=explain("agent.delta",{task_id:"n",route_id:"r",turn:1,kind:"text",text:"已确认登录入口。"});
explain("agent.delta",{task_id:"n",route_id:"r",turn:1,kind:"text",text:"接下来验证未登录时的访问条件。"});
explain("agent.tool_call",{task_id:"n",route_id:"r",calls:[{id:"c",name:"http_request"}]});
explain("agent.tool_result",{task_id:"n",route_id:"r",id:"c",ok:true,result:"HTTP 302"});
assert.equal(api.updatesOf(first)[0].text,"已确认登录入口。接下来验证未登录时的访问条件。");
explain("agent.delta",{task_id:"n",route_id:"r",turn:2,kind:"text",text:"匿名访问会跳转到登录页，尚不能认定存在越权。下一步核对认证后的响应。"});
assert.equal(api.updatesOf(first).length,2);
assert.match(api.updatesOf(first)[1].text,/匿名访问会跳转/);
explain("task.done",{task_id:"n"});
assert.match(api.summaryOf(first),/最后一次进展/);
assert.match(api.summaryOf(first),/尚不能认定存在越权/);
assert.equal(api.commentaryText('{"progress":"尚未完成'),"","不展示半截结构化决策");
assert.equal(api.commentaryText('{"progress":"已确认入口，准备验证访问条件。","analysis":"内部决策","actions":[{"command":"pwd"}]}'),"已确认入口，准备验证访问条件。" );
assert.equal(api.commentaryText('{"actions":[{"command":"pwd"}]}'),"","没有公开说明时不拿执行协议凑进度");
explain("agent.delta",{task_id:"n",route_id:"r",turn:3,kind:"text",text:'{"progress":"这一段需要重试"}'});
assert.equal(api.updatesOf(first).length,3);
explain("agent.delta",{task_id:"n",route_id:"r",turn:3,kind:"reset"});
assert.equal(api.updatesOf(first).length,2,"重试的未完成进展被正确撤销");
console.log("task commentary: persistent natural-language updates, structured progress, retries and honest final fallback passed");

// 同一任务不同路线/回合必须分别展开，迟到的结果仍归原步骤。
const phases=api.create();
let phaseSeq=0;
const phase=(type,detail)=>api.reduce(phases,{actor:"web",type,detail,seq:++phaseSeq});
phase("agent.turn",{task_id:"one",route_id:"r1",route:"solve",turn:1});
const grouped=phase("agent.tool_call",{task_id:"one",route_id:"r1",turn:1,calls:[{id:"late",name:"shell"}]});
phase("agent.turn",{task_id:"one",route_id:"r1",turn:2});
phase("agent.delta",{task_id:"one",route_id:"r1",turn:2,kind:"text",text:"新的独立验证"});
phase("agent.tool_result",{task_id:"one",route_id:"r1",id:"late",ok:true,result:"上一回合的结果"});
assert.equal(grouped.steps.size,2);
const parts=[...grouped.steps.values()];
assert.equal([...grouped.tools.values()][0].stepKey,parts[0].key);
assert.equal(parts[1].texts.size,1);
phase("agent.turn",{task_id:"one",route_id:"r2",turn:2});
assert.equal(grouped.steps.size,3,"不同路线同回合不合并");

first.summary="## 核实登录行为";
assert.match(api.summaryOf(first),/最后一次进展/,"只重复任务标题的摘要不能覆盖已有进展正文");
