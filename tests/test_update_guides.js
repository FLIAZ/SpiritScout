"use strict";
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const root={dataset:{},innerHTML:'',querySelectorAll(){return this.openItems || [];}};
const context=vm.createContext(require('./helpers/i18n').context({$:()=>root,esc:s=>String(s??'').replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]))}));
vm.runInContext(fs.readFileSync('src/spiritscout/web/static/js/update-guides.js','utf8'),context);
const render=s=>{context.input=s;vm.runInContext('UpdateGuides.render(input)',context);};
const source={installation:{kind:'source'},release:{tag:'v1.2.3'}};
render(source);
assert.match(root.innerHTML,/<details data-guide="source" open>/);
assert.match(root.innerHTML,/git fetch origin tag &quot;v1.2.3&quot;/);
assert.match(root.innerHTML,/docker compose pull spiritscout/);
assert.doesNotMatch(root.innerHTML,/reset --hard|down -v|pacman -Sy\s/);
root.innerHTML='user-expanded-dom';render(source);
assert.equal(root.innerHTML,'user-expanded-dom','普通轮询保留用户展开状态及命令选择');
root.openItems=[{dataset:{guide:'container'}}];
render({...source,release:{tag:'v1.2.4'}});
assert.match(root.innerHTML,/<details data-guide="container" open>/);
assert.doesNotMatch(root.innerHTML,/<details data-guide="source" open>/);
render({installation:{kind:'system_package',label:'Arch / pacman'}});
assert.match(root.innerHTML,/<details data-guide="arch" open>/);
render({installation:{kind:'source'},reason:'由进程管理器托管'});
assert.match(root.innerHTML,/<details data-guide="managed" open>/);
render({installation:{kind:'package'},release:{tag:'v1.2.3"; touch /tmp/bad'}});
assert.doesNotMatch(root.innerHTML,/touch \/tmp/);
console.log('update guides: installation matching, safe commands and tags, expansion retention passed');
