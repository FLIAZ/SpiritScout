"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const pending = [];
const nodes = new Map();
const root = {innerHTML:"", querySelector(selector) {
  if (!nodes.has(selector)) nodes.set(selector, {textContent:"", hidden:true, value:"", disabled:false, classList:{toggle(){}}});
  return nodes.get(selector);
}, replaceChildren() { this.innerHTML = ""; }};
const context = vm.createContext(require('./helpers/i18n').context({root, encodeURIComponent, api:(path,options) => new Promise((resolve,reject) => pending.push({path,options,resolve,reject}))}));
vm.runInContext(fs.readFileSync(require("node:path").join(__dirname,"../src/spiritscout/web/static/js/traffic-proxy.js"),"utf8"), context);
const controls = vm.runInContext('TrafficProxy.mount(root,"test-session")',context);
const flush = async () => { for (let i=0;i<8;i++) await Promise.resolve(); };
const status = state => ({available:true,status:state,records:0,error:""});
(async () => {
  const refresh = controls.refresh();
  pending.shift().resolve(status("stopped")); await refresh;
  const change = nodes.get("[data-proxy-enable]").onclick();
  pending.shift().reject(new Error("fixture launch failed")); await flush();
  pending.shift().resolve(status("stopped")); await change;
  assert.match(nodes.get("[data-proxy-message]").textContent,/fixture launch failed/,"状态刷新不能吞掉启动失败原因");
  const running = controls.refresh(); pending.shift().resolve(status("running")); await running;
  const reveal = nodes.get("[data-proxy-env]").onclick();
  const oldEnvironment = pending.shift();
  const stopped = controls.refresh(); pending.shift().resolve(status("stopped")); await stopped;
  oldEnvironment.resolve({environment:{HTTP_PROXY:"private-token"}}); await reveal;
  assert.equal(nodes.get("[data-proxy-environment] pre").textContent, "", "停止后的迟到凭据响应不能重新显示");
  assert.equal(nodes.get("[data-proxy-environment]").hidden, true);
  const late = controls.refresh(), lateResponse = pending.shift();
  controls.close(); lateResponse.resolve(status("running")); await late;
  assert.equal(root.innerHTML, "", "离页后迟到响应不能重建代理面板");
  const legacyControls = vm.runInContext('TrafficProxy.mount(root,"legacy-session")',context);
  const legacyRefresh = legacyControls.refresh();
  const legacyError = new Error("Unprocessable Content");
  legacyError.status = 422;
  legacyError.detail = [{input:"proxy",loc:["path","record_id"],type:"int_parsing"}];
  pending.shift().reject(legacyError); await legacyRefresh;
  assert.equal(nodes.get("[data-proxy-actions]").hidden, true, "旧后端不能暴露无效代理操作");
  assert.match(nodes.get("[data-proxy-status]").textContent,/当前后端未提供/);
  assert.match(nodes.get("[data-proxy-message]").textContent,/重启后端/);
  await legacyControls.refresh();
  assert.equal(pending.length,0,"旧后端不应每五秒重复请求未提供的代理接口");
  legacyControls.close();
  console.log("traffic proxy: persistent errors, stale credentials and unmount isolation passed");
})().catch(error => { console.error(error); process.exitCode=1; });
