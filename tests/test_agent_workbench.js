"use strict";
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const context=vm.createContext({SessionObserver:{resultSummary:d=>d.result||d.error||'',cleanText:v=>String(v||'')}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/spiritscout/web/static/js/agent-workbench.js'),'utf8'),context);
const api=vm.runInContext('AgentWorkbench',context),store=api.create();
const push=(actor,type,detail)=>api.reduce(store,{actor,type,detail,ts:'2026-10-17T00:00:00Z'});
push('master-abcd1234','agent.delta',{text:'主agent',kind:'reasoning'});
assert.equal(store.agents.size,0);
push('recon-abcd1234','agent.turn',{turn:1});
push('web-vuln-abcd1234','agent.turn',{turn:1});
push('recon-abcd1234','agent.delta',{route:'a',kind:'reasoning',text:'第一条分析'});
push('recon-abcd1234','agent.delta',{route:'a',kind:'reasoning',text:'续写'});
push('recon-abcd1234','agent.delta',{route:'b',kind:'reasoning',text:'并行路线'});
push('web-vuln-abcd1234','agent.delta',{kind:'text',text:'<script>alert(1)</script>'});
const recon=store.agents.get('recon-abcd1234');
assert.equal(recon.blocks.length,2);assert.equal(recon.blocks[0].text,'第一条分析续写');
assert.equal(store.agents.get('web-vuln-abcd1234').blocks.length,1);
push('recon-abcd1234','agent.delta',{route:'a',kind:'reset'});
assert.equal(recon.blocks.length,1);assert.equal(recon.blocks[0].text,'并行路线');
push('recon-abcd1234','model.started',{call_id:'1'});push('recon-abcd1234','model.started',{call_id:'2'});
push('recon-abcd1234','model.call',{call_id:'1'});assert.equal(recon.status,'模型生成中');
push('recon-abcd1234','agent.tool_result',{id:'missing',ok:false,error:'超时'});
assert.equal(recon.tools.get('missing').status,'失败');
push('recon-abcd1234','agent.conclude',{summary:'已确认结果'});
push('recon-abcd1234','task.done',{});assert.equal(recon.status,'已完成');assert.equal(recon.calls.size,0);
push('recon-abcd1234','agent.delta',{call_id:'new',kind:'text',text:'x'.repeat(30000)});
assert.equal(recon.blocks.at(-1).text.length,24000);assert.equal(recon.blocks.at(-1).clipped,true);
assert.equal(store.selected,'recon-abcd1234');
assert.equal(api.create().agents.size,0,'新会话不携带旧实例');
console.log('agent workbench: parallel actors/routes, fallback reset, tool failures, output bounds and session isolation passed');
